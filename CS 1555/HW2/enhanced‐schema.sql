DROP SCHEMA IF EXISTS apartment CASCADE;
CREATE SCHEMA apartment;
SET SCHEMA 'apartment';
CREATE DOMAIN "status" AS VARCHAR(12) CHECK (VALUE IN ('Open', 'Pending', 'In-Progress', 'Resolved', 'Closed'));

DROP TABLE IF EXISTS APARTMENT CASCADE;
DROP TABLE IF EXISTS "owner" CASCADE;
DROP TABLE IF EXISTS TENANT CASCADE;
DROP TABLE IF EXISTS PREVIOUS_ADDRESS CASCADE;
DROP TABLE IF EXISTS LEASE CASCADE;
DROP TABLE IF EXISTS MAINTENANCE_REQUEST CASCADE;
DROP TABLE IF EXISTS SIGNS CASCADE;
DROP TABLE IF EXISTS SUBMITS CASCADE;

CREATE TABLE APARTMENT (
    street VARCHAR(50) NOT NULL,
    city VARCHAR(50) NOT NULL,
    zipcode CHAR(5) NOT NULL,
    aptNumber INTEGER,
    inspectionPermitNo INTEGER NOT NULL,
    floor INTEGER NOT NULL,
    numBeds INTEGER NOT NULL DEFAULT 1,
    numBaths INTEGER NOT NULL DEFAULT 1,
    UNIQUE (inspectionPermitNo),
    CHECK (numBeds > 0),
    CHECK (numBaths > 0),
    PRIMARY KEY (aptNumber)
);



CREATE TABLE "owner" (
    "Name" VARCHAR(50),
    aptNumber INTEGER,
    street VARCHAR(50) NOT NULL,
    city VARCHAR(50) NOT NULL,
    zipcode CHAR(5) NOT NULL,
    PRIMARY KEY ("Name", aptNumber),
    FOREIGN KEY (aptNumber) REFERENCES APARTMENT(aptNumber) ON UPDATE CASCADE ON DELETE NO ACTION
);



CREATE TABLE TENANT (
    tenantID INTEGER,
    occupation VARCHAR(50),
    income DEC(8, 2),
    cellno VARCHAR(20),
    UNIQUE (cellno),
    CHECK (income > 0),
    PRIMARY KEY (tenantID)
);



CREATE TABLE PREVIOUS_ADDRESS (
    street VARCHAR(50),
    city VARCHAR(50),
    zipcode CHAR(5),
    tenantID INTEGER,
    PRIMARY KEY (street, city, zipcode, tenantID),
    FOREIGN KEY (tenantID) REFERENCES TENANT(tenantID) ON UPDATE CASCADE ON DELETE NO ACTION
);


CREATE TABLE LEASE (
    leaseNo INTEGER,
    startDate DATE NOT NULL,
    endDate DATE NOT NULL,
    payment DEC(8, 2) NOT NULL,
    aptNumber INTEGER NOT NULL,
    CHECK (startdate < enddate),
    PRIMARY KEY (leaseNo),
    FOREIGN KEY (aptNumber) REFERENCES APARTMENT(aptNumber) ON UPDATE CASCADE ON DELETE NO ACTION
);



CREATE TABLE MAINTENANCE_REQUEST (
    maintenanceID INTEGER,
    requestDate DATE NOT NULL,
    problem VARCHAR(50),
    description TEXT,
    status "status" DEFAULT 'Open',
    maintenanceRating INTEGER DEFAULT 5,
    lastUpdated TIMESTAMP NOT NULL,
    CHECK (lastUpdated >= requestDate),
    PRIMARY KEY (maintenanceID)
);


CREATE TABLE SIGNS (
    leaseNo INTEGER,
    tenantID INTEGER,
    renewalDate DATE NOT NULL,
    PRIMARY KEY (leaseNo, tenantID),
    FOREIGN KEY (leaseNo) REFERENCES LEASE(leaseNo) ON UPDATE CASCADE ON DELETE NO ACTION,
    FOREIGN KEY (tenantID) REFERENCES TENANT(tenantID) ON UPDATE CASCADE ON DELETE NO ACTION
);



CREATE TABLE SUBMITS (
    maintenanceID INTEGER,
    tenantID INTEGER NOT NULL,
    aptNumber INTEGER NOT NULL,
    PRIMARY KEY (maintenanceID),
    FOREIGN KEY (aptNumber) REFERENCES APARTMENT(aptNumber) ON UPDATE CASCADE ON DELETE NO ACTION,
    FOREIGN KEY (maintenanceID) REFERENCES MAINTENANCE_REQUEST(maintenanceID) ON UPDATE CASCADE ON DELETE NO ACTION
);


